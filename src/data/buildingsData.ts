export function findBuilding(idOrCodeOrAlias: string): Building | undefined {
  const q = idOrCodeOrAlias.toLowerCase();
  return CAMPUS_BUILDINGS.find(
    (b) =>
      b.id.toLowerCase() === q ||
      b.code.toLowerCase() === q ||
      b.name.toLowerCase() === q ||
      b.shortName.toLowerCase() === q ||
      (b.aliases && b.aliases.some((a) => a.toLowerCase() === q))
  );
}
